package Basics_of_JAVA;

public class ArithmeticOperationsOnInt {
    public static void main(String[] args) {
        int x = 39, y = 10;
        System.out.println(x + y);
        System.out.println(x - y);
        System.out.println(x * y);
        System.out.println(x / y);

        float a = 39.5f, b = 10.5f;
        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
    }
}
